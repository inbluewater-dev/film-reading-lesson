/** {이름} 자리를 채운다. 값이 없는 자리는 ‘없음’으로 둔다 */
export function renderPrompt(body: string, vars: Record<string, string | number | null | undefined>): string {
  return body.replace(/\{([^{}\s]+)\}/g, (m, name: string) => {
    if (!(name in vars)) return m;
    const v = vars[name];
    return v === null || v === undefined || v === '' ? '없음' : String(v);
  });
}

/** 템플릿에 모르는 자리 이름이 있는지 */
export function unknownVariables(kind: PromptKind, body: string): string[] {
  const known = PROMPT_VARIABLES[kind];
  return [...new Set([...body.matchAll(/\{([^{}\s]+)\}/g)].map((m) => m[1]))].filter((n) => !(n in known));
}
